export function generateQuestion(count = 4) {
	const shuffled = [...flags].sort(() => 0.5 - Math.random());
	const options = shuffled.slice(0, count);
	const correct = options[Math.floor(Math.random() * options.length)];
	return { options, correct };
}

export function generateGame(questionsCount = 10, optionsCount = 4) {
	if (questionsCount > flags.length) {
		throw new Error(
			'No se pueden generar más preguntas que el número total de items disponibles'
		);
	}
	const questions = [];
	for (let i = 0; i < questionsCount; i++) {
		questions.push(generateQuestion(optionsCount));
		if (questions.length > 1) {
			while (
				questions[i].correct.countryName ===
				questions[i - 1].correct.countryName
			) {
				questions[i] = generateQuestion(optionsCount);
			}
		}
	}
	return questions;
}
